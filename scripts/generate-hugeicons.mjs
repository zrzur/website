/**
 * Generate src/hugeicons.ts (inner SVG markup per icon) from Hugeicons free
 * "Stroke Rounded" (MIT), shared by the main site and the Discover site.
 *
 * Usage: node scripts/generate-hugeicons.mjs <path to @hugeicons/core-free-icons package>
 *
 * The package is read as data (its ESM files are parsed as text, never
 * imported), so it is not a dependency. Line weight is set by the <svg>.
 */
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

